import chalk from 'chalk';
import fs from 'fs-extra';
import path from 'path';
import { fileURLToPath } from 'url';
import { dirname } from 'path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

export async function createProject(config) {
  const { name, database, auth, cache, type, optimizations } = config;
  const projectPath = path.join(process.cwd(), name);

  // Check if directory already exists
  if (await fs.pathExists(projectPath)) {
    console.log(chalk.red(`  ✖ Directory "${name}" already exists.`));
    console.log('');
    process.exit(1);
  }

  console.log(chalk.gray(`  Creating project: ${chalk.white(name)}...`));

  // Create directory structure
  const dirs = [
    'src/app',
    'src/modules/example',
    'src/core/middleware',
    'src/core/database',
    'src/core/utils',
    'src/config',
  ];

  for (const dir of dirs) {
    await fs.ensureDir(path.join(projectPath, dir));
  }

  // Generate files
  await writePackageJson(projectPath, name, database, auth, cache);
  await writeMainJs(projectPath, type);
  await writeServerJs(projectPath);
  await writeRoutesJs(projectPath, auth);
  await writeEnvConfig(projectPath, database);
  await writeExampleModule(projectPath);
  await writeMiddleware(projectPath, auth);
  await writeDatabaseLayer(projectPath, database);
  await writeUtils(projectPath);
  await writeEnvFile(projectPath, database);
  await writeReadme(projectPath, name, database, auth, cache, type);
  await writeGitignore(projectPath);

  // Optional plugins
  if (auth) await writeAuthPlugin(projectPath);
  if (database === 'mysql') await writeMysqlPlugin(projectPath);
  if (database === 'sqlite') await writeSqlitePlugin(projectPath);
  if (cache) await writeCachePlugin(projectPath);
  if (optimizations) await writeLoggerPlugin(projectPath);

  console.log(chalk.green(`  ✔ Project created: ${chalk.bold(name)}`));
  console.log('');
  console.log(chalk.gray('  Next steps:'));
  console.log(chalk.cyan(`    cd ${name}`));
  console.log(chalk.cyan('    npm install'));
  console.log(chalk.cyan('    nexorix run'));
  console.log('');
}

