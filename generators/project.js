async function writeMiddleware(projectPath, auth) {
  const middlewarePath = path.join(projectPath, 'src', 'core', 'middleware');

  const authMiddleware = `import { config } from '../../config/env.js';

// Simple JWT verification without external dependency
// For production, install jsonwebtoken: npm install jsonwebtoken
export function authMiddleware(req, res) {
  const authHeader = req.headers['authorization'];

  if (!authHeader || !authHeader.startsWith('Bearer ')) {
    res.writeHead(401, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: 'Unauthorized — missing token' }));
    return false;
  }

  const token = authHeader.split(' ')[1];

  try {
    // Basic token validation (replace with jwt.verify in production)
    if (!token || token.length < 10) {
      throw new Error('Invalid token');
    }
    // Decode payload (base64 middle part)
    const parts = token.split('.');
    if (parts.length === 3) {
      const payload = JSON.parse(Buffer.from(parts[1], 'base64url').toString());
      if (payload.exp && payload.exp < Math.floor(Date.now() / 1000)) {
        throw new Error('Token expired');
      }
      req.user = payload;
    }
    return true;
  } catch (err) {
    res.writeHead(401, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: \`Unauthorized — \${err.message}\` }));
    return false;
  }
}
`;

  const errorMiddleware = `export function errorHandler(err, req, res) {
  const statusCode = err.statusCode || 500;
  const message = err.message || 'Internal Server Error';

  console.error(\`[error] \${req.method} \${req.url} — \${message}\`);

  res.writeHead(statusCode, { 'Content-Type': 'application/json' });
  res.end(JSON.stringify({
    error: message,
    path: req.url,
    timestamp: new Date().toISOString(),
  }));
}
`;

  await fs.writeFile(path.join(middlewarePath, 'auth.middleware.js'), authMiddleware);
  await fs.writeFile(path.join(middlewarePath, 'error.middleware.js'), errorMiddleware);
}

