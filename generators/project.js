async function writeCachePlugin(projectPath) {
  const pluginPath = path.join(projectPath, 'src', 'core', 'plugins', 'cache');
  await fs.ensureDir(pluginPath);

  const content = `/**
 * Cache Plugin — In-memory cache layer
 */

const store = new Map();
const ttlStore = new Map();

export const cache = {
  set(key, value, ttlSeconds = 300) {
    store.set(key, value);
    if (ttlSeconds > 0) {
      const existing = ttlStore.get(key);
      if (existing) clearTimeout(existing);
      const timer = setTimeout(() => {
        store.delete(key);
        ttlStore.delete(key);
      }, ttlSeconds * 1000);
      ttlStore.set(key, timer);
    }
  },

  get(key) {
    return store.get(key) ?? null;
  },

  has(key) {
    return store.has(key);
  },

  delete(key) {
    const timer = ttlStore.get(key);
    if (timer) clearTimeout(timer);
    store.delete(key);
    ttlStore.delete(key);
  },

  clear() {
    for (const timer of ttlStore.values()) clearTimeout(timer);
    store.clear();
    ttlStore.clear();
  },

  size() {
    return store.size;
  },

  stats() {
    return { size: store.size, keys: [...store.keys()] };
  },
};
`;
  await fs.writeFile(path.join(pluginPath, 'index.js'), content);
}

async function writeLoggerPlugin(projectPath) {
  const pluginPath = path.join(projectPath, 'src', 'core', 'plugins', 'logger');
  await fs.ensureDir(pluginPath);

  const content = `/**
 * Logger Plugin — Structured logging (replaces console.log)
 */

const LEVELS = { debug: 0, info: 1, warn: 2, error: 3 };
const currentLevel = LEVELS[process.env.LOG_LEVEL] ?? LEVELS.info;

function format(level, message, meta = {}) {
  const ts = new Date().toISOString();
  const hasMeta = Object.keys(meta).length > 0;
  return JSON.stringify({
    timestamp: ts,
    level,
    message,
    ...(hasMeta ? { meta } : {}),
  });
}

export const logger = {
  debug(message, meta = {}) {
    if (currentLevel <= LEVELS.debug) {
      process.stdout.write(format('debug', message, meta) + '\\n');
    }
  },

  info(message, meta = {}) {
    if (currentLevel <= LEVELS.info) {
      process.stdout.write(format('info', message, meta) + '\\n');
    }
  },

  warn(message, meta = {}) {
    if (currentLevel <= LEVELS.warn) {
      process.stderr.write(format('warn', message, meta) + '\\n');
    }
  },

  error(message, meta = {}) {
    if (currentLevel <= LEVELS.error) {
      process.stderr.write(format('error', message, meta) + '\\n');
    }
  },
};
`;
  await fs.writeFile(path.join(pluginPath, 'index.js'), content);
}
